-- Chatly group chat foundation. Safe additive migration; existing direct messages remain unchanged.
create table if not exists public.group_conversations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 80),
  description text not null default '' check (char_length(description) <= 500),
  avatar_url text,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.group_conversation_members (
  conversation_id uuid not null references public.group_conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  joined_at timestamptz not null default now(),
  last_read_at timestamptz,
  primary key (conversation_id, user_id)
);

create table if not exists public.group_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.group_conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 4000),
  reply_to bigint references public.group_messages(id) on delete set null,
  edited_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists group_members_user_idx on public.group_conversation_members(user_id, conversation_id);
create index if not exists group_messages_conversation_time_idx on public.group_messages(conversation_id, created_at desc);

alter table public.group_conversations enable row level security;
alter table public.group_conversation_members enable row level security;
alter table public.group_messages enable row level security;

drop policy if exists "Members can view group conversations" on public.group_conversations;
create policy "Members can view group conversations" on public.group_conversations
  for select to authenticated using (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = id and m.user_id = auth.uid())
  );

drop policy if exists "Authenticated users can create groups" on public.group_conversations;
create policy "Authenticated users can create groups" on public.group_conversations
  for insert to authenticated with check (created_by = auth.uid());

drop policy if exists "Group admins can update group details" on public.group_conversations;
create policy "Group admins can update group details" on public.group_conversations
  for update to authenticated using (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = id and m.user_id = auth.uid() and m.role in ('owner', 'admin'))
  ) with check (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = id and m.user_id = auth.uid() and m.role in ('owner', 'admin'))
  );

drop policy if exists "Members can view group membership" on public.group_conversation_members;
create policy "Members can view group membership" on public.group_conversation_members
  for select to authenticated using (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = conversation_id and m.user_id = auth.uid())
  );

drop policy if exists "Users can join groups they create" on public.group_conversation_members;
create policy "Users can join groups they create" on public.group_conversation_members
  for insert to authenticated with check (
    user_id = auth.uid() and role = 'owner' and
    exists (select 1 from public.group_conversations c
      where c.id = conversation_id and c.created_by = auth.uid())
  );

drop policy if exists "Group admins can add members" on public.group_conversation_members;
create policy "Group admins can add members" on public.group_conversation_members
  for insert to authenticated with check (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = conversation_id and m.user_id = auth.uid() and m.role in ('owner', 'admin'))
  );

drop policy if exists "Admins manage membership and users may leave" on public.group_conversation_members;
create policy "Admins manage membership and users may leave" on public.group_conversation_members
  for delete to authenticated using (
    user_id = auth.uid() or exists (
      select 1 from public.group_conversation_members m
      where m.conversation_id = conversation_id and m.user_id = auth.uid() and m.role in ('owner', 'admin'))
  );

drop policy if exists "Members can read group messages" on public.group_messages;
create policy "Members can read group messages" on public.group_messages
  for select to authenticated using (
    exists (select 1 from public.group_conversation_members m
      where m.conversation_id = group_messages.conversation_id and m.user_id = auth.uid())
  );

drop policy if exists "Members can send group messages" on public.group_messages;
create policy "Members can send group messages" on public.group_messages
  for insert to authenticated with check (
    sender_id = auth.uid() and exists (
      select 1 from public.group_conversation_members m
      where m.conversation_id = group_messages.conversation_id and m.user_id = auth.uid())
  );

drop policy if exists "Senders can edit group messages" on public.group_messages;
create policy "Senders can edit group messages" on public.group_messages
  for update to authenticated using (sender_id = auth.uid()) with check (sender_id = auth.uid());

drop policy if exists "Senders can delete group messages" on public.group_messages;
create policy "Senders can delete group messages" on public.group_messages
  for delete to authenticated using (sender_id = auth.uid());

-- Enable Realtime for group activity, if not already published.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'group_conversations') then
    execute 'alter publication supabase_realtime add table public.group_conversations';
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'group_conversation_members') then
    execute 'alter publication supabase_realtime add table public.group_conversation_members';
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'group_messages') then
    execute 'alter publication supabase_realtime add table public.group_messages';
  end if;
end
$$;
